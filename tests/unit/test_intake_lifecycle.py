def _create_experiment(
    client: TestClient, exp_id: str = "EXP_001", battery_id: str = "CELL_001"
) -> dict:
    resp = client.post(
        "/api/v1/experiments",
        json={"battery_id": battery_id, "experiment_id": exp_id, "name": "测试实验"},
    )
    assert resp.status_code == 200, resp.text
    return resp.json()["data"]


def _new_session_with_assets(client: TestClient, exp_id: str = "EXP_001") -> str:
    _create_experiment(client, exp_id)
    session = client.post(f"/api/v1/experiments/CELL_001/{exp_id}/intake-sessions").json()["data"]
    for role, fixture in (
        ("ELECTRICAL", "sample_electrical.xlsx"),
        ("ULTRASOUND", "sample_ultrasound.txt"),
    ):
        content = (FIXTURES / fixture).read_bytes()
        up = client.post(
            f"/api/v1/intake-sessions/{session['session_id']}/assets",
            files={"file": (fixture, content, "application/octet-stream")},
            data={"role": role},
        )
        assert up.status_code == 200, up.text
    det = client.post(f"/api/v1/intake-sessions/{session['session_id']}/detect")
    assert det.status_code == 200, det.text
    val = client.post(f"/api/v1/intake-sessions/{session['session_id']}/validate")
    assert val.status_code == 200, val.text
    return session["session_id"]


def _validated_session(client: TestClient, exp_id: str = "EXP_001") -> str:
    sid = _new_session_with_assets(client, exp_id)
    return sid


