    def test_t21_ambiguous_stops(self, env: tuple[TestClient, Path, Path]) -> None:
        client, _, _ = env
        _create_experiment(client, "EXP_001")
        sid = client.post("/api/v1/experiments/CELL_001/EXP_001/intake-sessions").json()["data"][
            "session_id"
        ]
        # ".txt" is ultrasound; craft ambiguous via two matches is registry-dependent —
        # force ambiguity by monkeypatching registry modalities
        engine = client.app.state.workbench_service.intake  # type: ignore[attr-defined]
        session = engine.load_session(sid)
        asset = engine.store_asset(
            session,
            role="ULTRASOUND",
            original_filename="both.txt",
            content=b"data",
        )
        import battery_workbench.intake.engine as engine_mod
        from battery_workbench.intake.engine import (
            ULTRASOUND_SUFFIXES,
        )

        original = set(ULTRASOUND_SUFFIXES)
        engine_mod.ULTRASOUND_SUFFIXES = {".txt", ".xlsx"}  # type: ignore[misc]
        try:
            (engine.staging_dir(sid) / asset.stored_filename).rename(
                engine.staging_dir(sid) / (asset.intake_asset_id + ".xlsx")
            )
            asset.stored_filename = asset.intake_asset_id + ".xlsx"
            engine.save_session(session)
            resp = client.post(f"/api/v1/intake-sessions/{sid}/detect")
            assert resp.status_code == 409
            assert resp.json()["error"]["code"] == "AMBIGUOUS_ADAPTER"
        finally:
            engine_mod.ULTRASOUND_SUFFIXES = original  # type: ignore[misc]

    def test_t22_content_over_extension(self, env: tuple[TestClient, Path, Path]) -> None:
        """extension/MIME is a hint; registry decides. A .txt with xlsx bytes is unsupported, not xlsx."""
